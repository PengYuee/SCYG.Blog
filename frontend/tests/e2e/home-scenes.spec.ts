test("query history updates results without returning to Hero", async ({ page }) => {
  await installReadFixtures(page)
  await gotoReady(page, "/", page.locator("#hero-profile-name"))
  await page.locator("#hero-search-input").fill("Edge")
  await page.locator("#hero-search-input").press("Enter")
  await expect(page.locator(".public-hero")).toBeHidden()
  await page.goBack()
  await expect(page).toHaveURL("/")
  await expect(page.locator("#content-search-input")).toHaveValue("")
  await expect(page.locator(".public-hero")).toBeHidden()
  await page.goForward()
  await expect(page.locator("#content-search-input")).toHaveValue("Edge")
  await expect(page.locator(".public-hero")).toBeHidden()
  await page.getByRole("banner").getByRole("button", { name: "主页", exact: true }).click()
  await expect(page.locator(".public-hero")).toBeVisible()
})

test("keeps both full search forms mounted and shares drafts across scene switches", async ({ page }) => {
  const health = observePageHealth(page)
  await page.emulateMedia({ reducedMotion: "reduce" })
  await installReadFixtures(page)
  const mutations = await installMutationRecorder(page)
  await gotoReady(page, "/", page.locator("#hero-profile-name"))

  const hero = page.locator(".public-hero")
  const content = page.locator("#blog-content")
  const heroInput = page.locator("#hero-search-input")
  const contentInput = page.locator("#content-search-input")
  await expect(page.locator('form[role="search"]')).toHaveCount(2)
  await expect(contentInput).toBeAttached()
  await expect(content).toBeHidden()
  await expect(page.getByRole("banner").getByRole("search")).toHaveCount(0)
  await heroInput.fill("尚未提交的关键词")
  await page.getByRole("button", { name: "进入内容区", exact: true }).click()
  await expect(hero).toBeHidden()
  await expect(content).toBeVisible()
  await expect(contentInput).toHaveValue("尚未提交的关键词")
  await expect(page.getByRole("complementary", { name: "搜索与筛选", exact: true }).getByRole("search")).toBeVisible()
  await expect(contentInput.locator("xpath=ancestor::form")).toHaveClass(/unified-search--sidebar/)
  await expect(contentInput.locator("xpath=ancestor::form")).not.toHaveClass(/unified-search--compact/)
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  expect(await content.evaluate((element) => {
    const header = document.querySelector("header")
    return header !== null && (element.firstElementChild?.getBoundingClientRect().top ?? 0) >= header.getBoundingClientRect().bottom
  })).toBe(true)
  await contentInput.fill("在内容场景修改的关键词")
  await page.getByRole("banner").getByRole("button", { name: "主页", exact: true }).click()
  await expect(hero).toBeVisible()
  await expect(content).toBeHidden()
  await expect(heroInput).toHaveValue("在内容场景修改的关键词")
  await expect(page).toHaveURL("/")
  expect(await page.evaluate(() => window.history.state.homeScene)).toBe("hero")
  await page.reload()
  await expect(hero).toBeVisible()
  await expect(content).toBeHidden()
  expect(mutations.requests).toEqual([])
  expectHealthy(health)
})

test("consumes the entering wheel gesture until idle and never exits content by scrolling up", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await installReadFixtures(page)
  await gotoReady(page, "/", page.locator("#hero-profile-name"))
  // Time is the behavior under test: freeze the idle timer, not the browser between assertions.
  await page.clock.install()
  await page.clock.pauseAt(new Date())
  const hero = page.locator(".public-hero")
  const content = page.locator("#blog-content")
  const point = await hero.boundingBox()
  if (point === null) throw new Error("Hero has no gesture surface")
  await page.mouse.move(point.x + 8, point.y + point.height / 2)
  await page.mouse.wheel(0, 500)
  await expect(content).toBeVisible()
  await expect(hero).toBeHidden()
  // Every event in a burst must be cancelled, including upward inertia.
  const swallowed = await content.evaluate((element) => [100, 300, -80].map((deltaY) => {
    const event = new WheelEvent("wheel", { deltaY, bubbles: true, cancelable: true })
    element.dispatchEvent(event)
    return event.defaultPrevented
  }))
  expect(swallowed).toEqual([true, true, true])
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  await page.clock.runFor(151)
  const afterIdle = await content.evaluate((element) => {
    const event = new WheelEvent("wheel", { deltaY: 100, bubbles: true, cancelable: true })
    element.dispatchEvent(event)
    return event.defaultPrevented
  })
  expect(afterIdle).toBe(false)
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }))
  await content.dispatchEvent("wheel", { deltaY: -500, bubbles: true, cancelable: true })
  await expect(hero).toBeHidden()
  await expect(content).toBeVisible()
  await page.getByRole("banner").getByRole("button", { name: "主页", exact: true }).click()
  await expect(hero).toBeVisible()
  await expect(content).toBeHidden()
})

test("excludes search controls and textarea wheels while preserving shared AI drafts", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await installReadFixtures(page)
  const mutations = await installMutationRecorder(page)
  await gotoReady(page, "/", page.locator("#hero-profile-name"))
  const hero = page.locator(".public-hero")
  const heroForm = hero.getByRole("search")
  const contentForm = page.locator('form.home-content-search[role="search"]')
  const heroInput = page.locator("#hero-search-input")
  await heroInput.dispatchEvent("wheel", { deltaY: 500, bubbles: true, cancelable: true })
  await expect(hero).toBeVisible()
  await heroForm.getByRole("button", { name: "AI 搜索", exact: true }).first().click()
  await expect(heroInput).toHaveJSProperty("tagName", "TEXTAREA")
  await expect(hero).toBeVisible()
  await heroInput.fill("保留多行问题\n第二行继续提问")
  await heroForm.getByRole("button", { name: "搜索选项", exact: true }).click()
  await page.locator("#hero-search-input-limit").fill("3")
  await heroInput.dispatchEvent("wheel", { deltaY: 500, bubbles: true, cancelable: true })
  await page.locator("#hero-search-input-limit").dispatchEvent("wheel", { deltaY: 500, bubbles: true, cancelable: true })
  await heroForm.getByRole("button", { name: "搜索选项", exact: true }).dispatchEvent("wheel", { deltaY: 500, bubbles: true, cancelable: true })
  await expect(hero).toBeVisible()
  await expect(page.locator("#blog-content")).toBeHidden()
  await page.getByTestId("hero-scroll-cue").click()
  const contentInput = page.locator("#content-search-input")
  await expect(contentInput).toHaveJSProperty("tagName", "TEXTAREA")
  await expect(contentInput).toHaveValue("保留多行问题\n第二行继续提问")
  await contentForm.getByRole("button", { name: "搜索选项", exact: true }).click()
  await expect(page.locator("#content-search-input-limit")).toHaveValue("3")
  await contentInput.fill("内容场景编辑后的问题")
  await page.locator("#content-search-input-limit").fill("2")
  await page.getByRole("banner").getByRole("button", { name: "主页", exact: true }).click()
  await expect(heroInput).toHaveValue("内容场景编辑后的问题")
  await expect(page.locator("#hero-search-input-limit")).toHaveValue("2")
  await expect(heroForm.getByRole("button", { name: "AI 搜索", exact: true }).first()).toHaveAttribute("aria-pressed", "true")
  expect(mutations.requests).toEqual([])
})

test("submits search once and restores content on reload and detail Back", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await installReadFixtures(page)
  const mutations = await installMutationRecorder(page)
  const searches: string[] = []
  page.on("request", (request) => {
    const url = new URL(request.url())
    if (url.pathname === "/api/v1/articles" && url.searchParams.get("q") === "Edge") searches.push(url.href)
  })
  await gotoReady(page, "/", page.locator("#hero-profile-name"))
  await page.locator("#hero-search-input").fill(" Edge ")
  await page.locator("#hero-search-input").press("Enter")
  await expect(page).toHaveURL((url) => url.pathname === "/" && url.searchParams.get("q") === "Edge")
  await expect(page.getByRole("heading", { name: "“Edge”的搜索结果", level: 2 })).toBeVisible()
  await expect(page.locator(".public-hero")).toBeHidden()
  expect(searches).toHaveLength(1)
  const results = page.locator("#home-results")
  expect(await results.evaluate((element) => {
    const header = document.querySelector("header")
    return header !== null && element.getBoundingClientRect().top >= header.getBoundingClientRect().bottom
  })).toBe(true)
  await page.reload()
  await expect(page.getByRole("heading", { name: "“Edge”的搜索结果", level: 2 })).toBeVisible()
  await expect(page.locator(".public-hero")).toBeHidden()
  expect(searches).toHaveLength(2)
  await page.locator("#home-results").getByRole("link", { name: /在 Edge 中验证中文博客的完整阅读体验/ }).last().click()
  await expect(page.getByRole("heading", { name: "在 Edge 中验证中文博客的完整阅读体验", level: 1 })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole("heading", { name: "“Edge”的搜索结果", level: 2 })).toBeVisible()
  await expect(page.locator(".public-hero")).toBeHidden()
  expect(await page.evaluate(() => window.history.state.homeScene)).toBe("content")
  expect(searches).toHaveLength(2)
  // 再次从首屏搜索必须回到结果开头，不能恢复先前的内容阅读位置。
  await page.evaluate(() => window.scrollTo({ top: document.documentElement.scrollHeight, behavior: "instant" }))
  expect(await page.evaluate(() => window.scrollY)).toBeGreaterThan(0)
  await page.getByRole("banner").getByRole("button", { name: "主页", exact: true }).click()
  await page.locator("#hero-search-input").press("Enter")
  await expect(page.locator("#content-search-input")).toBeVisible()
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  expect(mutations.requests).toEqual([])
})
